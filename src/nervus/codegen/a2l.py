"""ASAM MCD-2 MC (A2L) files: the description calibration tools (INCA, CANape, ...) need.

Every tunable parameter of the generated code becomes a ``CHARACTERISTIC`` (scalar ``VALUE`` or array
``VAL_BLK``) and every block signal a ``MEASUREMENT``. Units, limits and descriptions come from the model
workspace. All data are ``FLOAT64_IEEE`` (the generated code uses ``double``).

Addresses are only known after the ECU program is linked. ``generate_a2l`` writes placeholders relative to the
struct symbols; :func:`fill_addresses` replaces them using the symbol table of the built binary (``nm``).
"""

from __future__ import annotations

import math
import re
import shutil
import subprocess
from pathlib import Path
from typing import TYPE_CHECKING

from nervus import __version__

if TYPE_CHECKING:
    from nervus.codegen.generator import CGenerator

DOUBLE = 8
_ADDR = re.compile(r"0x0 /\* @(\w+)\+(\d+) \*/")


_ASAM_TYPES = {"real_T": "FLOAT64_IEEE", "real32_T": "FLOAT32_IEEE", "boolean_T": "UBYTE", "int8_T": "SBYTE",
               "uint8_T": "UBYTE", "int16_T": "SWORD", "uint16_T": "UWORD", "int32_T": "SLONG",
               "uint32_T": "ULONG"}  # fmt: skip


def _limit(v: float | None, default: float) -> str:
    if v is None or not math.isfinite(v):
        return f"{default:g}"
    return repr(float(v))


def _ident(name: str) -> str:
    return re.sub(r"[^0-9A-Za-z_.]", "_", name)


def generate_a2l(gen: CGenerator) -> str:
    """The A2L text for a generated model (called by the code generator)."""
    pfx = gen.prefix
    ws = gen.model.diagram.root.workspace
    lines = [
        "ASAP2_VERSION 1 71",
        f'/begin PROJECT {pfx} "Generated by Nervus {__version__}"',
        f'  /begin MODULE {pfx} "Model {gen.model.diagram.name}"',
        '    /begin MOD_COMMON ""',
        "      BYTE_ORDER MSB_LAST",
        "      ALIGNMENT_FLOAT64_IEEE 8",
        "    /end MOD_COMMON",
        '    /begin COMPU_METHOD CM_IDENTICAL "identity" IDENTICAL "%12.6" ""',
        "    /end COMPU_METHOD",
        "    /begin RECORD_LAYOUT RL_FLOAT64 FNC_VALUES 1 FLOAT64_IEEE ROW_DIR DIRECT",
        "    /end RECORD_LAYOUT",
    ]
    units: set[str] = set()
    layouts = {"FLOAT64_IEEE"}
    offset = 0
    for f in gen.param_fields():  # constants in ROM are not calibratable, so they are not in the A2L file
        var = ws.variable(f.name) if f.name in ws else None
        unit = var.unit if var is not None else ""
        desc = (var.description if var is not None and var.description else f.comment).replace('"', "'")
        lo = _limit(var.min if var is not None else None, -1e12)
        hi = _limit(var.max if var is not None else None, 1e12)
        d = f.dtype
        asam = _ASAM_TYPES.get(d.c_type, "FLOAT64_IEEE")
        if asam not in layouts:
            layouts.add(asam)
            lines += [
                f"    /begin RECORD_LAYOUT RL_{asam} FNC_VALUES 1 {asam} ROW_DIR DIRECT",
                "    /end RECORD_LAYOUT",
            ]
        scaled = d.kind == "fixed" and not d.is_integer
        method = "CM_IDENTICAL"
        if scaled:  # the tool shows physical values: phys = slope * stored + bias
            method = f"CM_{_ident(f.name)}"
            lines += [
                f'    /begin COMPU_METHOD {method} "{d.name}" LINEAR "%12.6" "{unit}"',
                f"      COEFFS_LINEAR {d.slope!r} {d.bias!r}",
                "    /end COMPU_METHOD",
            ]
            lo, hi = _limit(max(d.min, float(lo)), d.min), _limit(min(d.max, float(hi)), d.max)
        elif unit:
            method = f"CM_{_ident(unit) or 'unit'}"
            if method not in units:
                units.add(method)
                lines += [
                    f'    /begin COMPU_METHOD {method} "unit {unit}" IDENTICAL "%12.6" "{unit}"',
                    "    /end COMPU_METHOD",
                ]
        kind = "VALUE" if f.size == 1 else "VAL_BLK"
        lines += [
            f'    /begin CHARACTERISTIC {pfx}_P.{f.name} "{desc}"',
            f"      {kind} 0x0 /* @{pfx}_P+{offset} */ RL_{asam if asam != 'FLOAT64_IEEE' else 'FLOAT64'} 0 {method} {lo} {hi}",
        ]
        if f.size > 1:
            lines.append(f"      NUMBER {f.size}")
        lines.append(f'      SYMBOL_LINK "{pfx}_P.{f.name}" 0')
        lines.append("    /end CHARACTERISTIC")
        offset += f.size * f.nbytes
    offset = 0
    m = gen.model
    from nervus.core.dictionary import named_signals

    try:
        named = {v: k for k, v in named_signals(m.diagram).items()}  # (path, port) → signal name
    except Exception:  # a name used twice: no named measurements
        named = {}
    dictionary = m.diagram.root.signals
    for i, ws_out in enumerate(m.out_widths):
        for p, w in enumerate(ws_out):
            field = gen.signal_var(i, p).split(".", 1)[1]
            signal = named.get((m.names[i], p))
            obj = dictionary[signal] if signal is not None and signal in dictionary else None
            method, lo, hi, desc = "CM_IDENTICAL", "-1e12", "1e12", m.names[i]
            if obj is not None:
                lo, hi = _limit(obj.min, -1e12), _limit(obj.max, 1e12)
                desc = (obj.description or m.names[i]).replace('"', "'")
                if obj.unit:
                    method = f"CM_{_ident(obj.unit) or 'unit'}"
                    if method not in units:
                        units.add(method)
                        lines += [
                            f'    /begin COMPU_METHOD {method} "unit {obj.unit}" IDENTICAL "%12.6" "{obj.unit}"',
                            "    /end COMPU_METHOD",
                        ]
            for k in range(w):
                suffix = f"[{k}]" if w > 1 else ""
                label = f"{signal}{suffix}" if signal is not None else f"{pfx}_B.{field}{suffix}"
                lines += [
                    f'    /begin MEASUREMENT {label} "{desc}"',
                    f"      FLOAT64_IEEE {method} 0 0 {lo} {hi}",
                    f"      ECU_ADDRESS 0x0 /* @{pfx}_B+{offset + k * DOUBLE} */",
                    f'      SYMBOL_LINK "{pfx}_B.{field}" {k * DOUBLE}',
                    "    /end MEASUREMENT",
                ]
            offset += w * DOUBLE
    lines += ["  /end MODULE", "/end PROJECT", ""]
    return "\n".join(lines)


def symbol_addresses(binary: str | Path) -> dict[str, int]:
    """Global data symbols of a compiled binary, from ``nm`` (leading underscores on macOS are removed)."""
    nm = shutil.which("nm")
    if nm is None:
        raise FileNotFoundError("nm not found")
    out = subprocess.run([nm, "-g", str(binary)], capture_output=True, text=True, check=True).stdout
    symbols: dict[str, int] = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in "BDSCbdsc":
            symbols[parts[2].lstrip("_") if parts[2].startswith("_") else parts[2]] = int(parts[0], 16)
    return symbols


def fill_addresses(a2l: str, symbols: dict[str, int]) -> str:
    """Replace the placeholder addresses with real ones (struct symbol address + field offset)."""

    def sub(m: re.Match[str]) -> str:
        base = symbols.get(m.group(1))
        if base is None:
            return m.group(0)
        return f"0x{base + int(m.group(2)):X}"

    return _ADDR.sub(sub, a2l)
